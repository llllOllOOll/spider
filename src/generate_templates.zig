//! Internal: build-time tool that writes the embedded templates file.
//! Usage: generate-templates <source_dir> <output_file>. It walks
//! `source_dir` and writes a Zig file declaring `EmbeddedTemplates`, a
//! struct with one `@embedFile` field per .html and .md file found, and
//! `spider_manifest`: what each template reads from a view's data
//! (render/manifest.zig), for `Ctx.viewChecked`; and `elroy`: the
//! templates Elroy compiles to Zig functions (render/elroy/codegen.zig).

const std = @import("std");
const manifest = @import("render/manifest.zig");
const elroy = @import("render/elroy/codegen.zig");
pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const allocator = init.arena.allocator();
    var args_it = try std.process.Args.Iterator.initAllocator(init.minimal.args, allocator);
    defer args_it.deinit();
    _ = args_it.next(); // Skip program name
    const source_dir = args_it.next() orelse {
        std.debug.print("Usage: generate-templates <source_dir> <output_file>\n", .{});
        return error.InvalidArgs;
    };
    const output_file = args_it.next() orelse {
        std.debug.print("Usage: generate-templates <source_dir> <output_file>\n", .{});
        return error.InvalidArgs;
    };
    var output = try std.ArrayList(u8).initCapacity(allocator, 4096);
    defer output.deinit(allocator);
    try output.appendSlice(allocator, "// Generated file - DO NOT EDIT MANUALLY\n");
    try output.appendSlice(allocator, "// This file is automatically generated by Spider's generateEmbeddedTemplates\n");
    const source_dir_line = try std.fmt.allocPrint(allocator, "// Source directory: {s}\n\n", .{source_dir});
    defer allocator.free(source_dir_line);
    try output.appendSlice(allocator, source_dir_line);
    try output.appendSlice(allocator, "pub const EmbeddedTemplates = struct {\n");
    const cwd = std.Io.Dir.cwd();
    var dir = try cwd.openDir(io, source_dir, .{ .iterate = true });
    defer dir.close(io);
    var walker = try dir.walk(allocator);
    defer walker.deinit();
    var template_count: usize = 0;
    var sources: std.ArrayList(manifest.Source) = .empty;
    // Each template's text and file, for Elroy to write slices of it.
    var embeds: std.ArrayList(struct { text: []const u8, path: []const u8 }) = .empty;
    while (try walker.next(io)) |entry| {
        if (entry.kind != .file) continue;
        if (!std.mem.endsWith(u8, entry.path, ".html") and
            !std.mem.endsWith(u8, entry.path, ".md")) continue;
        // Names and @embedFile paths use '/' on every system (the walk
        // gives '\' on Windows); the file is still read by its own path.
        var path_buf: [std.fs.max_path_bytes]u8 = undefined;
        const embed_path = slashPath(entry.path, std.fs.path.sep, &path_buf);
        var field_name_buf: [256]u8 = undefined;
        var alias_buf: [256]u8 = undefined;
        const names = try generateFieldName(embed_path, &field_name_buf, &alias_buf);
        if (std.mem.endsWith(u8, entry.path, ".html")) {
            const text = try dir.readFileAlloc(io, entry.path, allocator, .limited(8 * 1024 * 1024));
            try sources.append(allocator, .{ .name = try allocator.dupe(u8, names.primary), .text = text });
            if (names.alias) |alias| try sources.append(allocator, .{ .name = try allocator.dupe(u8, alias), .text = text });
            try embeds.append(allocator, .{ .text = text, .path = try allocator.dupe(u8, embed_path) });
        }
        const line = try std.fmt.allocPrint(allocator, "    {s}: []const u8 = @embedFile(\"{s}\"),\n", .{ names.primary, embed_path });
        defer allocator.free(line);
        try output.appendSlice(allocator, line);
        template_count += 1;
        if (names.alias) |alias| {
            // Legacy name kept alongside the PascalCase-stripped one for
            // backward compatibility (see spider-render skill, "Components
            // Folder" patch): old callers of c.view("components_X", ...)
            // keep working after the primary field lost the dir prefix.
            const alias_line = try std.fmt.allocPrint(allocator, "    {s}: []const u8 = @embedFile(\"{s}\"),\n", .{ alias, embed_path });
            defer allocator.free(alias_line);
            try output.appendSlice(allocator, alias_line);
        }
    }
    // What each template reads, for c.viewChecked (render/manifest.zig).
    try output.appendSlice(allocator, "\n    pub const spider_manifest = struct {\n");
    var analyzer = try manifest.Analyzer.init(allocator, sources.items);
    for (sources.items) |src| {
        const uses = try analyzer.analyze(src.text);
        try manifest.writeZig(&output, allocator, src.name, uses);
    }
    try output.appendSlice(allocator, "    };\n");
    // The templates Elroy compiles; the others render with the interpreter.
    try output.appendSlice(allocator, "\n    pub const elroy = struct {\n        const std = @import(\"std\");\n        const E = @import(\"spider\").elroy;\n\n");
    var by_name: elroy.Sources = .{};
    for (sources.items) |src| try by_name.put(allocator, src.name, src.text);
    var unit = elroy.Unit.init(allocator, &by_name);
    for (embeds.items) |e| try unit.addSource(e.text, try std.fmt.allocPrint(allocator, "@embedFile(\"{s}\")", .{e.path}));
    var compiled: usize = 0;
    for (sources.items) |src| {
        if (try elroy.generate(&unit, &output, src.name, src.text)) compiled += 1;
    }
    // The component and layout functions the templates call.
    try output.appendSlice(allocator, unit.code.items);
    try output.appendSlice(allocator, "    };\n");
    try output.appendSlice(allocator, "};\n");
    // zig fmt the whole file: the generated code is emitted unindented.
    const formatted = blk: {
        const z = try allocator.dupeSentinel(u8, output.items, 0);
        var tree = try std.zig.Ast.parse(allocator, z, .{});
        if (tree.errors.len > 0) break :blk output.items; // shows where it is wrong
        break :blk try tree.renderAlloc(allocator);
    };
    const out_file = try cwd.createFile(io, output_file, .{});
    defer out_file.close(io);
    var buffer: [4096]u8 = undefined;
    var writer: std.Io.File.Writer = .init(out_file, io, &buffer);
    try writer.interface.writeAll(formatted);
    try writer.interface.flush();
    std.debug.print("Ride the lightning — {d} templates forged in {s} ({d} compiled by Elroy)\n", .{ template_count, output_file, compiled });
}

/// `path` with its separator `sep` replaced by '/', in `buffer` (as long as
/// `path`). On systems whose separator is already '/', `path` itself.
fn slashPath(path: []const u8, sep: u8, buffer: []u8) []const u8 {
    if (sep == '/') return path;
    const out = buffer[0..path.len];
    for (path, out) |ch, *o| o.* = if (ch == sep) '/' else ch;
    return out;
}

const FieldNames = struct {
    primary: []const u8,
    // Legacy dir-prefixed name, only set when it differs from primary
    // (i.e. the PascalCase rule actually dropped a directory prefix).
    alias: ?[]const u8 = null,
};

fn generateFieldName(path: []const u8, buffer: []u8, alias_buffer: []u8) !FieldNames {
    const no_ext = if (std.mem.endsWith(u8, path, ".html"))
        path[0 .. path.len - 5]
    else if (std.mem.endsWith(u8, path, ".md"))
        path[0 .. path.len - 3]
    else
        path;

    if (std.mem.indexOf(u8, no_ext, "views/")) |idx| {
        const after = no_ext[idx + "views/".len ..];
        const file = std.fs.path.basename(after);
        const before = no_ext[0..idx];
        const dir = std.fs.path.basename(before);

        if (dir.len == 0) {
            // Normalize full path after views/ — bills/index → bills_index
            var j: usize = 0;
            for (after) |c| {
                if (j >= buffer.len) break;
                buffer[j] = if (c == '/' or c == '-') '_' else c;
                j += 1;
            }
            return .{ .primary = buffer[0..j] };
        }

        if (std.mem.eql(u8, dir, file)) {
            return .{ .primary = try std.fmt.bufPrint(buffer, "{s}", .{file}) };
        }
        if (file.len > 0 and file[0] >= 'A' and file[0] <= 'Z') {
            return .{ .primary = try std.fmt.bufPrint(buffer, "{s}", .{file}) };
        }
        return .{ .primary = try std.fmt.bufPrint(buffer, "{s}_{s}", .{ dir, file }) };
    }

    // shared/templates/
    var remaining = no_ext;
    if (std.mem.startsWith(u8, remaining, "shared/templates/")) {
        remaining = remaining["shared/templates/".len..];
    }

    // PascalCase basename (e.g. components/EntrarFragment.html) is a component:
    // keep the bare name, same convention as the views/ branch above, so
    // c.view("EntrarFragment", ...) matches the generated field directly.
    const base = std.fs.path.basename(remaining);
    if (base.len > 0 and base[0] >= 'A' and base[0] <= 'Z') {
        const primary = try std.fmt.bufPrint(buffer, "{s}", .{base});

        var j: usize = 0;
        for (remaining) |c| {
            if (j >= alias_buffer.len) break;
            alias_buffer[j] = if (c == '/' or c == '-') '_' else c;
            j += 1;
        }
        const legacy = alias_buffer[0..j];
        if (std.mem.eql(u8, legacy, primary)) {
            return .{ .primary = primary };
        }
        return .{ .primary = primary, .alias = legacy };
    }

    var j: usize = 0;
    for (remaining) |c| {
        buffer[j] = if (c == '/' or c == '-') '_' else c;
        j += 1;
    }
    return .{ .primary = buffer[0..j] };
}

const testing = std.testing;

test "a template path with Windows separators gives the same names and embed path as one with '/'" {
    const native = "features\\store\\views\\home.html";
    var path_buf: [256]u8 = undefined;
    const path = slashPath(native, '\\', &path_buf);
    try testing.expectEqualStrings("features/store/views/home.html", path);

    var a: [256]u8 = undefined;
    var b: [256]u8 = undefined;
    var c: [256]u8 = undefined;
    var d: [256]u8 = undefined;
    const from_windows = try generateFieldName(path, &a, &b);
    const from_posix = try generateFieldName("features/store/views/home.html", &c, &d);
    try testing.expectEqualStrings(from_posix.primary, from_windows.primary);
    try testing.expectEqualStrings("store_home", from_windows.primary);
}

test "on a system whose separator is '/', a backslash in a file name is kept" {
    var buf: [64]u8 = undefined;
    try testing.expectEqualStrings("odd\\name.html", slashPath("odd\\name.html", '/', &buf));
}
