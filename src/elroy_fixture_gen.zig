//! Build-time tool behind the Elroy parity test: compiles the templates of
//! src/render/elroy/fixtures.zig with Elroy and writes them to the file
//! named by the first argument (elroy_parity_test.zig imports it).

const std = @import("std");
const codegen = @import("render/elroy/codegen.zig");
const fixtures = @import("render/elroy/fixtures.zig");

// internal: a build step of Spider's own tests.
pub fn main(init: std.process.Init) !void {
    const alc = init.arena.allocator();
    var args = init.minimal.args.iterate();
    _ = args.skip();
    const out_path = args.next() orelse return error.MissingOutputPath;

    var out: std.ArrayList(u8) = .empty;
    try out.appendSlice(alc, "// Generated by src/elroy_fixture_gen.zig.\nconst std = @import(\"std\");\nconst E = @import(\"spider\").elroy;\n\n");
    var sources: codegen.Sources = .{};
    for (fixtures.components) |c| try sources.put(alc, c.name, c.src);
    var unit = codegen.Unit.init(alc, &sources);
    // The fixtures' texts as string constants: Elroy writes slices of them.
    for (fixtures.cases) |c| try unit.addSource(c.src, try std.fmt.allocPrint(alc, "\"{f}\"", .{std.zig.fmtString(c.src)}));
    var it = sources.valueIterator();
    while (it.next()) |v| try unit.addSource(v.*, try std.fmt.allocPrint(alc, "\"{f}\"", .{std.zig.fmtString(v.*)}));
    var compiled: std.ArrayList(u8) = .empty;
    for (fixtures.cases) |c| {
        if (try codegen.generate(&unit, &out, c.name, c.src)) {
            try compiled.print(alc, "    \"{s}\",\n", .{c.name});
        }
    }
    try out.appendSlice(alc, unit.code.items);
    try out.print(alc, "\npub const compiled = [_][]const u8{{\n{s}}};\n", .{compiled.items});

    const file = try std.Io.Dir.cwd().createFile(init.io, out_path, .{});
    defer file.close(init.io);
    var buf: [4096]u8 = undefined;
    var w = file.writer(init.io, &buf);
    try w.interface.writeAll(out.items);
    try w.interface.flush();
}
